/** Hoot, the existing mascot, placed with his feet at (x, y). */
export function hoot(P, x, y, s, id) {
  const inner = mascot({ rim: true, id })
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<title[^>]*>[^<]*<\/title>/, '')
    .replace(`fill="${C.rim}" stroke="${C.rim}"`, `fill="${P.rim}" stroke="${P.rim}"`);
  return `<g transform="translate(${f(x - 128 * s)} ${f(y - 246 * s)}) scale(${s})">${inner}</g>`;
}

/** A cookie with chips. */
function cookie(P, x, y, r, bite = false) {
  const chips = [
    [-0.35, -0.3, 0.17],
    [0.25, -0.1, 0.14],
    [-0.15, 0.35, 0.15],
    [0.38, 0.38, 0.12],
  ]
    .map(([dx, dy, k]) => `<circle cx="${f(x + dx * r)}" cy="${f(y + dy * r)}" r="${f(r * k)}" fill="${P.chip}"/>`)
    .join('');
  const body = bite
    ? `<path d="M${f(x + r * 0.96)} ${f(y - r * 0.3)}A${r} ${r} 0 1 1 ${f(x + r * 0.3)} ${f(y - r * 0.96)}a${f(r * 0.28)} ${f(r * 0.28)} 0 0 0 ${f(r * 0.3)} ${f(r * 0.35)}a${f(r * 0.26)} ${f(r * 0.26)} 0 0 0 ${f(r * 0.36)} ${f(r * 0.31)}Z" fill="${P.cookie}" stroke="${P.cookieEdge}" stroke-width="${f(Math.max(1.5, r * 0.1))}"/>`
    : `<circle cx="${x}" cy="${y}" r="${r}" fill="${P.cookie}" stroke="${P.cookieEdge}" stroke-width="${f(Math.max(1.5, r * 0.1))}"/>`;
  return `<g>${body}${chips}</g>`;
}

