/** palette.css: the roles mixed by Monsoon's --mode, so .dark sections and the theme toggle both work. */
export function paletteCss() {
  const mix = (n, d) => `color-mix(in oklab, ${n} calc(var(--mode) * 100%), ${d})`;
  const roles = ROLES.map((k) => `  --k-${k}: ${mix(NIGHT[k], DAWN[k])};`).join('\n');
  return `/* Generated by scripts/build-docs.mjs from scripts/storybook.mjs: the
   storybook palette, dawn in light mode and night in dark mode. */
:root, .theme, .dark, .light, [data-theme] {
${roles}
  --k-tint: ${C.amber};
}
`;
}

// ---------- Small helpers ----------

const f = (n) => Number(n.toFixed(1));
function rng(seed) {
  let s = seed;
  return () => (s = (s * 16807) % 2147483647) / 2147483647;
}
const FONT = "Fraunces, 'Iowan Old Style', Georgia, serif";
const SANS = "'Nunito Sans', 'Segoe UI', system-ui, sans-serif";

function wrapSvg(inner, { w, h, title, id, cls = '', inline = false, ratio }) {
  const labelled = title ? ` role="img" aria-labelledby="${id}-t"` : ' aria-hidden="true"';
  const t = title ? `<title id="${id}-t">${title}</title>` : '';
  const pr = ratio ? ` preserveAspectRatio="${ratio}"` : '';
  if (inline) return `<svg class="${cls}" viewBox="0 0 ${w} ${h}"${pr}${labelled} focusable="false">${t}${inner}</svg>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}"${labelled}>${t}${inner}</svg>\n`;
}

function stars(P, seed, n, w, h, { cls = 'tw', min = 0.8, max = 2.2 } = {}) {
  const r = rng(seed);
  let out = '';
  for (let i = 0; i < n; i++) {
    const x = f(r() * w);
    const y = f(r() * h);
    const rad = f(min + r() * (max - min));
    const o = f(0.45 + r() * 0.55);
    if (rad > 1.9 && i % 3 === 0) {
      // a few four point sparkles
      const s = rad * 2.2;
      out += `<path class="${cls} ${cls}-${i % 3}" d="M${x} ${f(y - s)}Q${x} ${y} ${f(x + s)} ${y}Q${x} ${y} ${x} ${f(y + s)}Q${x} ${y} ${f(x - s)} ${y}Q${x} ${y} ${x} ${f(y - s)}Z" fill="${P.star}" opacity="${o}"/>`;
    } else out += `<circle class="${cls} ${cls}-${i % 3}" cx="${x}" cy="${y}" r="${rad}" fill="${P.star}" opacity="${o}"/>`;
  }
  return `<g>${out}</g>`;
}

function sparkle(P, x, y, s, color = P.amber) {
  return `<path d="M${x} ${y - s}Q${x} ${y} ${x + s} ${y}Q${x} ${y} ${x} ${y + s}Q${x} ${y} ${x - s} ${y}Q${x} ${y} ${x} ${y - s}Z" fill="${color}"/>`;
}

/** A soft organic blob behind spot illustrations. */
function blob(P, cx, cy, rx, ry, seed = 3, fill = P.blob) {
  const r = rng(seed);
  const pts = [];
  const n = 9;
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const k = 0.9 + r() * 0.16;
    pts.push([cx + Math.cos(a) * rx * k, cy + Math.sin(a) * ry * k]);
  }
  let d = '';
  for (let i = 0; i < n; i++) {
    const p0 = pts[(i - 1 + n) % n];
    const p1 = pts[i];
    const p2 = pts[(i + 1) % n];
    const p3 = pts[(i + 2) % n];
    if (i === 0) d += `M${f(p1[0])} ${f(p1[1])}`;
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return `<path d="${d}Z" fill="${fill}"/>`;
}

function radial(id, color, o = 0.75) {
  return `<radialGradient id="${id}"><stop offset="0" stop-color="${color}" stop-opacity="${o}"/><stop offset=".45" stop-color="${color}" stop-opacity="${f(o * 0.35)}"/><stop offset="1" stop-color="${color}" stop-opacity="0"/></radialGradient>`;
}

