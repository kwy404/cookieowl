/** A house of the website town: a pitched roof, a browser bar under the eaves and lit windows. */
function house(P, { x, y, w, h, seed = 1, jars = 1, roof = 'peak', door = true, chimney = false }) {
  const r = rng(seed);
  const sw = 3;
  let out = '';
  const peak = roof === 'peak' ? h * 0.42 : 0;
  if (chimney) out += `<rect x="${x + w * 0.68}" y="${y - h - peak * 0.75}" width="${w * 0.12}" height="${peak * 0.7}" fill="${P.wall2}" stroke="${P.ink}" stroke-width="${sw}"/>`;
  out += `<rect x="${x}" y="${y - h}" width="${w}" height="${h}" fill="${P.wall}" stroke="${P.ink}" stroke-width="${sw}"/>`;
  out += `<rect x="${x}" y="${y - h}" width="${f(w * 0.18)}" height="${h}" fill="${P.wall2}" opacity=".8"/>`;
  if (roof === 'peak') out += `<path d="M${x - 10} ${y - h + 2}L${x + w / 2} ${f(y - h - peak)}L${x + w + 10} ${y - h + 2}Z" fill="${P.roof}" stroke="${P.ink}" stroke-width="${sw}" stroke-linejoin="round"/>`;
  else out += `<rect x="${x - 6}" y="${y - h - 10}" width="${w + 12}" height="12" rx="3" fill="${P.roof}" stroke="${P.ink}" stroke-width="${sw}"/>`;
  // the browser bar
  const by = y - h + 8;
  out += `<rect x="${x + 7}" y="${by}" width="${w - 14}" height="13" rx="6.5" fill="${P.paper}" stroke="${P.ink}" stroke-width="2"/><circle cx="${x + 15}" cy="${by + 6.5}" r="2.2" fill="#e8705a"/><circle cx="${x + 22}" cy="${by + 6.5}" r="2.2" fill="${P.amber}"/><circle cx="${x + 29}" cy="${by + 6.5}" r="2.2" fill="#6fbf73"/><rect x="${x + 36}" y="${by + 4}" width="${f(Math.max(6, w - 52))}" height="5" rx="2.5" fill="${P.ink}" opacity=".18"/>`;
  // windows
  const cols = Math.max(1, Math.floor((w - 16) / 30));
  const rows = Math.max(1, Math.floor((h - 34 - (door ? 30 : 0)) / 34));
  const ww = 18;
  const gap = (w - cols * ww) / (cols + 1);
  let jarLeft = jars;
  for (let j = 0; j < rows; j++) {
    for (let i = 0; i < cols; i++) {
      const wx = x + gap + i * (ww + gap);
      const wy = y - h + 30 + j * 34;
      const lit = r() > 0.28;
      out += `<rect class="${lit ? 'win-lit' : ''}" x="${f(wx)}" y="${wy}" width="${ww}" height="22" rx="3" fill="${lit ? P.win : P.winOff}" stroke="${P.ink}" stroke-width="2.4"/><path d="M${f(wx + ww / 2)} ${wy}v22M${f(wx)} ${wy + 11}h${ww}" stroke="${P.ink}" stroke-width="1.6" opacity=".55"/><rect x="${f(wx - 3)}" y="${wy + 22}" width="${ww + 6}" height="4" rx="1.5" fill="${P.wall2}" stroke="${P.ink}" stroke-width="1.6"/>`;
      if (lit && jarLeft > 0 && (j === rows - 1 || r() > 0.6)) {
        out += jar(P, wx + ww / 2, wy + 22, 0.55);
        jarLeft--;
      }
    }
  }
  if (door) out += `<path d="M${f(x + w / 2 - 11)} ${y}V${y - 22}a11 11 0 0 1 22 0V${y}" fill="${P.roof}" stroke="${P.ink}" stroke-width="2.6"/><circle cx="${f(x + w / 2 + 6)}" cy="${y - 10}" r="1.6" fill="${P.amber}"/>`;
  return `<g class="house">${out}</g>`;
}

