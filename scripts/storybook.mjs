export const ICON_NAMES = Object.keys(ICONS);

/** One icon as a standalone SVG file. */
export function iconFile(name, theme) {
  const ink = theme === 'dark' ? '#efe6cf' : C.ink;
  const { t, l } = ICONS[name];
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="48" height="48" aria-hidden="true"><g fill="${C.amber}" transform="translate(.8 .8)">${t}</g><g fill="none" stroke="${ink}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${l}</g></svg>\n`;
}

/** The inline sprite symbol: the line follows currentColor, the tint --k-tint. */
export function iconSymbol(name) {
  const { t, l } = ICONS[name];
  return `<symbol id="k-${name}" viewBox="0 0 24 24"><g fill="var(--k-tint)" transform="translate(.8 .8)">${t}</g><g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${l}</g></symbol>`;
}

/** A sheet of every icon, for the README and the art index. */
export function iconSheet(theme) {
  const ink = theme === 'dark' ? '#efe6cf' : C.ink;
  const bg = theme === 'dark' ? '#0c1230' : '#fffaf0';
  const cols = Math.ceil(ICON_NAMES.length / 3);
  const cell = 64;
  const rows = Math.ceil(ICON_NAMES.length / cols);
  const cells = ICON_NAMES.map((n, i) => {
    const { t, l } = ICONS[n];
    const x = (i % cols) * cell + 12;
    const y = Math.floor(i / cols) * cell + 12;
    return `<g transform="translate(${x} ${y}) scale(1.6667)"><g fill="${C.amber}" transform="translate(.8 .8)">${t}</g><g fill="none" stroke="${ink}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${l}</g></g>`;
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${cols * cell} ${rows * cell}" width="${cols * cell}" height="${rows * cell}" role="img" aria-labelledby="is-${theme}-t"><title id="is-${theme}-t">The cookieowl icon family: ${ICON_NAMES.length} icons with rounded navy lines and an amber tint</title><rect width="100%" height="100%" rx="18" fill="${bg}"/>${cells}</svg>\n`;
}
